LOCK TABLE users IN ACCESS EXCLUSIVE MODE;

CREATE TABLE device_token_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    session_version BIGINT NOT NULL,
    latest_claim BOOLEAN,
    CONSTRAINT uk_device_token_claims_token_user UNIQUE (token_hash, user_id),
    CONSTRAINT uk_device_token_claims_latest UNIQUE (token_hash, latest_claim),
    CONSTRAINT ck_device_token_claims_latest CHECK (latest_claim IS NULL OR latest_claim),
    CONSTRAINT fk_device_token_claims_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

INSERT INTO device_token_claims (token_hash, user_id, session_version, latest_claim)
SELECT encode(sha256(convert_to(device_token, 'UTF8')), 'hex'),
       id, session_version, CASE WHEN count(*) OVER (PARTITION BY device_token) = 1 THEN TRUE END
FROM users
WHERE device_token IS NOT NULL;

UPDATE users u
SET device_token = NULL
FROM device_token_claims c
WHERE c.user_id = u.id AND c.latest_claim IS NULL;

ALTER TABLE users ADD CONSTRAINT uk_users_device_token UNIQUE (device_token);

CREATE INDEX idx_device_token_claims_user ON device_token_claims (user_id);
